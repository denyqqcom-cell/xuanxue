    fun calc(lunar: Lunar): Result {
        val yearZhi = lunar.yearZhiExact   // 农历年地支
        val month = lunar.month
        val day = lunar.day
        val timeZhi = lunar.timeZhi        // 时辰地支
        val y = YEAR_WEIGHT[yearZhi] ?: 0.0
        val m = MONTH_WEIGHT[month] ?: 0.0
        val d = DAY_WEIGHT[day] ?: 0.0
        val h = HOUR_WEIGHT[timeZhi] ?: 0.0
        val total = (y + m + d + h) * 10
        val liang = total.toInt() / 10
        val qian = (total - liang * 10).toInt()
        val key = when {
            liang >= 2 && qian > 0 -> "${liang}.$qian"
            else -> "$liang.0"
        }
        val text = "${liang}两" + if (qian > 0) "${qian}钱" else "整"
        return Result(total / 10.0, text, POEMS[key] ?: "")
    }
